"""First power budget. Every input is an estimate until measured; run to rewrite
docs/power-budget.md. The circuit is the band's, so the inputs are the ones in manent-band: only the
cells differ."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from mechanical.pendant_mech.checks import envelope_report  # noqa: E402

V_CELL = 3.7          # nominal cell voltage
BUCK_EFF = 0.85       # assumed efficiency of the 1.8 V buck at these loads
USABLE = 0.80         # share of the rated capacity counted on
TARGET_DAYS, STRETCH_DAYS = 2, 5

# (name, low, nominal, high, source). "rail": milliwatts at the 1.8 V rail. "cell": milliamps from the cell.
RECORDING = [
    ("rail", "CPU, Opus at 15 / 30 / 50 % duty of 2.6 mA at 3 V", 1.15, 2.3, 3.9, "vendor figure x assumed duty"),
    ("rail", "PDM interface and 32 MHz oscillator", 1.5, 1.5, 1.5, "estimate"),
    ("rail", "Two microphones, 120 / 120 / 310 uA each at 1.8 V", 0.43, 0.43, 1.12, "datasheet"),
    ("rail", "Flash program and erase, averaged", 0.36, 0.36, 0.5, "estimate"),
    ("cell", "Bright light, 0.2 / 0.5 / 1.0 mA", 0.2, 0.5, 1.0, "design choice"),
]
LISTENING = [
    ("rail", "Microphone A waiting for sound: analog 20 uA / digital 110 / 137 uA", 0.036, 0.198, 0.247, "datasheet"),
    ("rail", "Microphone B asleep, 0.8 uA", 0.0014, 0.0014, 0.0014, "datasheet"),
    ("rail", "Microcontroller asleep, clock and memory kept, 2 / 3 / 6 uA", 0.0036, 0.0054, 0.0108, "estimate"),
]
ALWAYS = [   # drawn in both states
    ("cell", "Bluetooth link kept alive", 0.010, 0.015, 0.030, "estimate"),
    ("cell", "Power chip itself", 0.001, 0.002, 0.005, "estimate"),
    ("cell", "Steady glow, 0.03 / 0.05 / 0.1 mA", 0.03, 0.05, 0.1, "design choice"),
    ("rail", "Bleed resistor on the microphone rail, 470 k at 1.8 V", 0.0069, 0.0069, 0.0069, "calculated"),
]
UPLOAD_MAH_PER_RECORDED_HOUR = 0.19   # 7.2 MB at an assumed 400 kbit/s
DAYS = {"quiet": 0.15, "typical": 0.25, "noisy": 0.50}   # share of the 24 hours with sound worth recording
STANDBY_UA = {"muted: microphones and light off, link kept": 20, "off, button wakes it (ship mode)": 0.37}


def at_cell(rows, col):
    """Milliamps from the cell for one column (0 low, 1 nominal, 2 high)."""
    return sum(r[2 + col] / BUCK_EFF / V_CELL if r[0] == "rail" else r[2 + col] for r in rows)


def average_ma(share, col=1):
    rec = at_cell(RECORDING + ALWAYS, col) + UPLOAD_MAH_PER_RECORDED_HOUR
    return share * rec + (1 - share) * at_cell(LISTENING + ALWAYS, col)


def table(title, rows, total):
    out = [f"## {title}", "", "| Contributor | Low | Nominal | High | Source |", "| --- | --- | --- | --- | --- |"]
    out += [f"| {n} | {a:g} {u} | {b:g} {u} | {c:g} {u} | {s} |"
            for kind, n, a, b, c, s in rows for u in [("mW" if kind == "rail" else "mA")]]
    ma = [at_cell(total, i) for i in range(3)]
    return out + [f"| **At the cell** ({V_CELL} V, {BUCK_EFF:.0%} conversion of the rail terms) | "
                  + " | ".join(f"**{m:.2f} mA**" for m in ma) + " | |", ""]


def main():
    cells = {}
    for key in ("A", "B"):
        e = envelope_report(key)
        cells[f"{e['cell']['capacity_mah']} mAh (envelope {e['envelope']})"] = e["cell"]["capacity_mah"]
    first = next(iter(cells.values()))
    out = ["# Power budget", "",
           "Generated by `tools/power_budget.py`. Nothing here is measured: the inputs are vendor",
           "figures, datasheet values and assumptions, each marked in the table. The first bench",
           "session on a development kit replaces them. Rows in mW are drawn from the 1.8 V rail,",
           "rows in mA straight from the cell. The circuit is the band's and so are these figures:",
           "only the cells are the pendant's.", ""]
    out += table("While there is sound: recording", RECORDING + ALWAYS, RECORDING + ALWAYS)
    out += table("In silence: waiting for sound", LISTENING + ALWAYS, LISTENING + ALWAYS)
    out += ["## Days between charges", "",
            f"Usable capacity is taken as {USABLE:.0%} of the rating. Upload costs {UPLOAD_MAH_PER_RECORDED_HOUR} mAh per recorded hour.",
            "The share is the part of the 24 hours with sound worth recording; the three shares are",
            "the ones in the `mnemo-band` design document, not measurements of anybody's day.", "",
            "| Cell | Draw | " + " | ".join(f"{k} ({v:.0%})" for k, v in DAYS.items()) + " |",
            "| --- | --- | " + " | ".join("---" for _ in DAYS) + " |"]
    for name, mah in cells.items():
        for col, label in ((0, "low"), (1, "nominal"), (2, "high")):
            days = [mah * USABLE / average_ma(s, col) / 24 for s in DAYS.values()]
            out.append(f"| {name} | {label} | " + " | ".join(f"{d:.1f} days" for d in days) + " |")
    typical = average_ma(DAYS["typical"])
    light = ALWAYS[2][3] + DAYS["typical"] * RECORDING[4][3]
    worst = first * USABLE / average_ma(DAYS["noisy"], 2) / 24
    out += ["", f"The requirement is {TARGET_DAYS} days and the stretch goal {STRETCH_DAYS}. On the smaller cell the typical day",
            f"at nominal draw averages {typical:.2f} mA; the worst case in the table (noisy day, high draw) gives {worst:.1f} days.",
            f"The light takes {light / typical:.0%} of the typical day: {ALWAYS[2][3]} mA of glow around the clock",
            f"and {RECORDING[4][3]} mA while recording.", "",
            "## Not listening", "", f"| State | Current | {first} mAh cell lasts |", "| --- | --- | --- |"]
    for k, v in STANDBY_UA.items():
        days = first * USABLE / (v * 24 / 1000)
        out.append(f"| {k} | {v} uA | " + (f"{days:.0f} days |" if days < 730 else "years: the cell's own leakage decides |"))
    out += ["", "The muted figure is an estimate; the ship-mode figure is the power chip's documented one.", "",
            "## What to measure first", "",
            "1. Opus encoder duty cycle on the nRF54L15 at complexity 0: it is the largest term and a guess.",
            "2. How much of a real day wakes the microphone, and how much of that the energy gate keeps.",
            "3. Light: the currents at which other people can see the glow and the bright state through the stone, for each of the three colours.",
            "4. PDM and oscillator current while recording.",
            "5. Link current with the final connection interval, and what the 32.768 kHz crystal saves.", ""]
    ROOT.joinpath("docs", "power-budget.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
